import numpy as np
import pytest

from shorgul.audio import write_wav
from shorgul.audit.stability import grade, stability
from shorgul.health.check import check, nearest_condition
from shorgul.degrade.telephony import phone_channel
from shorgul.degrade.packet_loss import apply_packet_loss
import pandas as pd


def _speech(n=16000 * 4, seed=0):
    rng = np.random.default_rng(seed)
    t = np.arange(n) / 16000
    env = (np.sin(2 * np.pi * 3 * t) > 0).astype(np.float32)
    x = env * (0.2 * np.sin(2 * np.pi * 300 * t) + 0.05 * rng.standard_normal(n))  # wideband-ish
    x += 0.002 * rng.standard_normal(n)  # mic noise floor: real recordings are never digital silence
    x[:3200] = 0
    return x.astype(np.float32)


PROFILES = pd.DataFrame({"condition": ["clean", "phone", "loss_5", "traffic_5", "market_0"],
                         "snr_db": [30, 31, 32, 20, 12.6], "hf_ratio": [0.003, 2e-6, 4e-5, 3e-6, 3e-6]})


def test_stability_basic():
    assert stability("a b c", "a b c", "hi") == 0
    assert stability("abc", "", "hi") == 1.0
    assert 0 < stability("नमस्ते सर", "नमस्ते", "hi") < 1
    assert [grade(x) for x in (0.0, 0.03, 0.07, 0.15, 0.5)] == ["A", "B", "C", "D", "F"]


def test_health_detects_band_and_dropouts():
    x = _speech()
    h_clean = check(x)
    h_phone = check(phone_channel(x))
    lossy, _ = apply_packet_loss(phone_channel(x), 0.08, np.random.default_rng(1))
    h_loss = check(lossy)
    assert h_clean.hf_ratio > h_phone.hf_ratio * 10
    assert h_loss.dropout_pct > 2 and h_phone.dropout_pct < 0.5
    assert h_clean.clipping_pct == 0
    assert nearest_condition(h_clean, PROFILES) == "clean"
    assert nearest_condition(h_loss, PROFILES) == "loss_5"
    assert nearest_condition(h_phone, PROFILES) in {"phone", "traffic_5", "market_0"}


def test_mock_audit_end_to_end(tmp_path, monkeypatch):
    from shorgul.audit import run as audit_run
    from shorgul.audit.report import render
    from shorgul.asr.cache import Cache
    folder = tmp_path / "calls"
    for i in range(3):
        write_wav(folder / f"call_{i}.wav", _speech(seed=i))
    monkeypatch.setattr(audit_run.Cache, "default", classmethod(lambda cls, mock=False: Cache(tmp_path / "c.sqlite")))
    noises = {"traffic": np.random.default_rng(5).standard_normal(16000 * 10).astype(np.float32) * 0.1,
              "market": np.random.default_rng(6).standard_normal(16000 * 10).astype(np.float32) * 0.1}
    res = audit_run.run_audit(folder, "hinglish", "prisma-v3.0", max_calls=0, mock=True, out=tmp_path / "out",
                              conditions=["phone", "loss_5", "market_0"], noises=noises)
    s = res.summary
    assert len(res.clips) == 3 and len(res.rows) == 9
    assert s["grade"] in "ABCDF" and list(s["per_condition"]["condition"]) == ["phone", "loss_5", "market_0"]
    assert len(s["worst"]) == 3 and any(f["fix"].startswith("Entity repair") for f in s["fixes"])
    report = render(res, tmp_path / "out")
    html = report.read_text(encoding="utf-8")
    assert "MOCK DATA" in html and "data:image/png;base64" in html and html.count("<audio") == 6 and "http" not in html.split("<main>")[1].split("Generated by")[0]


def test_audit_refuses_billed_calls_over_cap(tmp_path, monkeypatch):
    from shorgul.audit import run as audit_run
    from shorgul.asr.cache import Cache
    folder = tmp_path / "calls"
    write_wav(folder / "a.wav", _speech())
    monkeypatch.setattr(audit_run.Cache, "default", classmethod(lambda cls, mock=False: Cache(tmp_path / "c.sqlite")))
    with pytest.raises(RuntimeError, match="max-calls"):  # real Prisma, cap 0 -> nothing is sent
        audit_run.run_audit(folder, "hi", "prisma-v3.0", max_calls=0, mock=False, out=tmp_path / "o",
                            conditions=["phone"], noises={})


def test_long_digital_silence_is_not_packet_loss():
    x = _speech()
    x[16000:24000] = 0  # 500 ms VAD-gated silence in the middle
    assert check(x).dropout_pct < 0.5


def test_quick_audit_mock_and_billing(tmp_path):
    from shorgul.asr.base import ASRResult
    from shorgul.asr.cache import Cache
    from shorgul.audit.quick import load_clip, quick_audit
    noises = {"traffic": np.random.default_rng(7).standard_normal(16000 * 8).astype(np.float32) * 0.1,
              "market": np.random.default_rng(8).standard_normal(16000 * 8).astype(np.float32) * 0.1}
    audio = _speech()
    res = quick_audit(audio, "hinglish", "prisma-v3.0", mock=True, cache=Cache(tmp_path / "m.sqlite"), noises=noises)
    assert [r["condition"] for r in res.rows] == ["original", "phone", "loss_5", "traffic_5", "market_0"]
    assert res.billed_calls == 0 and res.grade in "ABCDF"

    class Billed:
        billed, name, n = True, "prisma-v3.0", 0

        def transcribe(self, audio, params):
            Billed.n += 1
            return ASRResult("₹4,500 की 5 मार्च", "ok", 0.1)

    c = Cache(tmp_path / "r.sqlite")
    first = quick_audit(audio, "hinglish", "prisma-v3.0", mock=False, backend=Billed(), cache=c, noises=noises)
    again = quick_audit(audio, "hinglish", "prisma-v3.0", mock=False, backend=Billed(), cache=c, noises=noises)
    assert first.billed_calls == 5 and again.billed_calls == 0 and Billed.n == 5  # cache: never billed twice
    with pytest.raises(ValueError, match="30"):
        load_clip(_wav(np.zeros(16000 * 31, dtype=np.float32)))


def _wav(x):
    import io
    import soundfile as sf
    b = io.BytesIO()
    sf.write(b, x, 16000, format="WAV", subtype="PCM_16")
    return b.getvalue()
