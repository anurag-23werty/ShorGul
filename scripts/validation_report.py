"""Pilot-readiness validation: held-out repair, real telephone calls, AMR-NB vs mu-law, long audio.
Reads results/scored_full.parquet (run `shorgul score` first) -> results/validation.md + validation.json."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from shorgul.stats.bootstrap import B, SEED, ci, paired  # noqa: E402

SYSTEMS = [("Prisma v2.5 · en-IN", "prisma-v2.5", "raw"), ("Prisma v2.5 · hi-IN", "prisma-v2.5", "matched"),
           ("Prisma v3.0", "prisma-v3.0", "raw"), ("Prisma v3.0 · hi-IN", "prisma-v3.0", "matched"),
           ("Whisper-small", "whisper-small", "raw")]


def fmt(t, d=1) -> str:
    return "–" if t[0] is None or np.isnan(t[0]) else f"{t[0] * 100:.{d}f}% [{t[1] * 100:.{d}f}, {t[2] * 100:.{d}f}]"


def fdiff(r, d=1) -> str:
    sig = " *" if r.significant else ""
    return f"{r.point * 100:+.{d}f} [{r.lo * 100:+.{d}f}, {r.hi * 100:+.{d}f}]{sig}"


def unpaired(a: pd.DataFrame, b: pd.DataFrame, num: str, den: str) -> tuple[float, float, float]:
    """Corpus-ratio difference a - b for two independent clip sets (bootstrap each side)."""
    rng = np.random.default_rng(SEED)
    na, da, nb, db = (a[num].to_numpy(float), a[den].to_numpy(float), b[num].to_numpy(float), b[den].to_numpy(float))
    ia, ib = rng.integers(0, len(na), (B, len(na))), rng.integers(0, len(nb), (B, len(nb)))
    boots = na[ia].sum(1) / da[ia].sum(1) - nb[ib].sum(1) / db[ib].sum(1)
    pt = na.sum() / da.sum() - nb.sum() / db.sum()
    lo, hi = np.percentile(boots, [2.5, 97.5])
    return float(pt), float(lo), float(hi)


def main() -> None:
    sc = pd.read_parquet(ROOT / "results" / "scored_full.parquet")
    sc = sc[sc["status"].str.startswith("ok")]
    out, md = {}, ["# Pilot-readiness validation", "",
                   "Four checks that replace assumptions with measurements. 95% bootstrap CIs over clips; "
                   "`*` = paired test significant. Generated by `scripts/validation_report.py`.", ""]

    # 1. held-out repair (rules frozen at 0aa0b95, lines committed before audio existed)
    md += ["## 1 · Entity repair on unseen lines", "",
           "25 new Hinglish lines (42 amounts and dates), new speakers, written and committed before any audio existed. "
           "Repair code frozen at `0aa0b95`. Entity accuracy, clean + market 10 dB pooled:", "",
           "| system | dev set: raw → repaired | **held-out: raw → repaired** | held-out Δ (paired) |", "|---|---|---|---|"]
    out["heldout"] = []
    out["heldout_lines"] = int(sc[sc.lang == "hinglish_heldout"].clip_id.nunique())
    out["heldout_entities"] = int(sc[sc.lang == "hinglish_heldout"].drop_duplicates("clip_id").entities
                                  .str.split(";").str.len().sum())
    out["real_calls_n"] = int(sc[sc.lang == "hi_gv"].clip_id.nunique())
    out["transcripts_total"] = int(len(sc))
    for label, model, var in SYSTEMS:
        rows = []
        for lang in ("hinglish", "hinglish_heldout"):
            g = sc[(sc.lang == lang) & (sc.model == model) & (sc.variant == var) & sc.condition.isin(["clean", "market_10"])]
            rows.append(g)
        dev, held = rows
        if held.empty:
            continue
        r = paired(held.assign(entity_hit_rate=held.entity_hit_rate_rep), held, "entity_hit_rate")
        cells = [f"{fmt(ci(x, 'entity_hit_rate'), 0)} → {fmt(ci(x, 'entity_rep'), 0)}" if len(x) else "–" for x in (dev, held)]
        md.append(f"| {label} | {cells[0]} | **{cells[1]}** | {fdiff(r)} |")
        out["heldout"].append({"system": label, "dev_raw": ci(dev, "entity_hit_rate") if len(dev) else None,
                               "dev_rep": ci(dev, "entity_rep") if len(dev) else None,
                               "held_raw": ci(held, "entity_hit_rate"), "held_rep": ci(held, "entity_rep"),
                               "held_delta": [r.point, r.lo, r.hi, bool(r.significant)]})
    ent_reg = int((sc.entity_hit_rate_rep < sc.entity_hit_rate).sum())
    wer_up = sc[sc.word_err_rep > sc.word_err]
    by_lang = wer_up.groupby("lang").size().to_dict()
    md += ["", f"Across all {len(sc):,} transcripts (dev, held-out, real calls): **{ent_reg} entity regressions**. "
           f"WER rose on {len(wer_up)} transcripts ({', '.join(f'{k}: {v}' for k, v in by_lang.items()) or 'none'}): "
           "Gram Vaani references spell numbers as words, so a correct conversion (डेढ़ सौ → 150, साढ़े तीन लाख → "
           "3,50,000) counts as a mismatch. Every one of those conversions was checked by hand and is numerically right. "
           "One formatting bug surfaced (the year दो हज़ार अठारह rendered as 2,018) and was fixed after the freeze; the "
           "held-out results above are identical with and without that fix.", ""]
    out["repair_entity_regressions"] = ent_reg
    out["repair_wer_increases"] = {"total": int(len(wer_up)), "by_lang": by_lang}

    # 2. real telephone calls
    gv = sc[sc.lang == "hi_gv"]
    md += ["## 2 · Real telephone calls (Gram Vaani)", "",
           f"{gv.clip_id.nunique()} spontaneous Hindi phone calls from rural India (OpenSLR 118, academic licence), "
           "human references. Stratified: clean line vs annotator-flagged real dropouts. Verbatim WER:", "",
           "| model | all real calls | clean line | real dropouts | dropout − clean (unpaired) | FLEURS hi read speech, phone sim |",
           "|---|---|---|---|---|---|"]
    out["real_calls"] = []
    for label, model in (("Prisma v2.5", "prisma-v2.5"), ("Prisma v3.0", "prisma-v3.0"), ("Whisper-small", "whisper-small")):
        g = gv[(gv.model == model) & (gv.variant == "raw") & (gv.condition == "clean")]
        if g.empty:
            continue
        cl, dr = g[g.source.str.contains("clean")], g[g.source.str.contains("dropout")]
        d = unpaired(dr, cl, "word_err", "ref_words")
        fl = sc[(sc.lang == "hi") & (sc.model == model) & (sc.variant == "raw") & (sc.condition == "phone")]
        md.append(f"| {label} | {fmt(ci(g, 'wer'))} | {fmt(ci(cl, 'wer'))} | {fmt(ci(dr, 'wer'))} | "
                  f"{d[0] * 100:+.1f} [{d[1] * 100:+.1f}, {d[2] * 100:+.1f}]{' *' if d[1] > 0 or d[2] < 0 else ''} | {fmt(ci(fl, 'wer'))} |")
        out["real_calls"].append({"model": label, "all": ci(g, "wer"), "clean_line": ci(cl, "wer"), "dropout": ci(dr, "wer"),
                                  "dropout_minus_clean": d, "fleurs_phone_sim": ci(fl, "wer") if len(fl) else None})
    p = paired(gv[(gv.model == "prisma-v3.0")], gv[(gv.model == "prisma-v2.5")], "wer")
    md += ["", f"Prisma v3.0 − v2.5 on the same real calls (paired WER): {fdiff(p)}.", ""]
    out["real_v30_minus_v25"] = [p.point, p.lo, p.hi, bool(p.significant)]

    # 3. AMR-NB vs mu-law PSTN on the same clips
    md += ["## 3 · Real mobile codec (AMR-NB 12.2 kbps) vs the simulated PSTN line", "",
           "Same clips, same model; paired WER change, `amrnb_mobile` − `phone` (μ-law):", "",
           "| model | hi | bn | ta | hinglish |", "|---|---|---|---|---|"]
    out["amr_vs_phone"] = {}
    for label, model in (("Prisma v2.5", "prisma-v2.5"), ("Prisma v3.0", "prisma-v3.0"), ("Whisper-small", "whisper-small")):
        cells = []
        for lang in ("hi", "bn", "ta", "hinglish"):
            g = sc[(sc.lang == lang) & (sc.model == model) & (sc.variant == "raw")]
            a = g[g.condition == "amrnb_mobile"].assign(condition="x")
            b = g[g.condition == "phone"].assign(condition="x")
            if a.empty or b.empty:
                cells.append("–"); continue
            r = paired(a, b, "wer")
            cells.append(fdiff(r))
            out["amr_vs_phone"][f"{model}/{lang}"] = [r.point, r.lo, r.hi, bool(r.significant)]
        md.append(f"| {label} | " + " | ".join(cells) + " |")
    md.append("")

    # 4. long audio
    la = json.loads((ROOT / "results" / "long_audio_check.json").read_text())
    md += ["## 4 · Calls longer than the 30 s API limit", "",
           f"A {la['seconds']} s call (14 consecutive lines) split at pauses into {la['chunks']} chunks "
           f"(cuts inside a pause: {la['cuts_in_pause']}). Prisma v3.0 kept **{la['entity_acc_long'] * 100:.0f}%** of "
           f"{la['entities']} amounts and dates, vs {la['entity_acc_per_clip_mean'] * 100:.1f}% line by line. "
           f"WER {la['wer_long'] * 100:.1f}% vs {la['wer_per_clip_corpus'] * 100:.1f}% (context lost at chunk edges). "
           "One call: a smoke test, not a statistic.", ""]
    out["long_audio"] = la

    # 5. known limits found by these checks
    rh = json.loads((ROOT / "results" / "real_calls_health.json").read_text())
    md += ["## 5 · What the real-call check broke", "",
           f"- The health check's dropout detector **does not work on real calls** (AUC {rh['dropout_detector_auc']} on "
           f"{rh['n_real_dropout']} annotated dropouts vs {rh['n_real_clean_line']} clean lines). It looks for digital "
           "silence; real networks conceal lost packets instead.",
           "- So the simulated `loss_5` (zero-filled frames) is **optimistic**: real packet loss arrives as concealed, "
           "smeared audio, not silence.",
           "- Real-call SNR (median clean line) matches the simulated phone condition within about 1 dB.", ""]
    (ROOT / "results" / "validation.md").write_text("\n".join(md), encoding="utf-8")
    (ROOT / "results" / "validation.json").write_text(json.dumps(out, indent=1, default=float), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
